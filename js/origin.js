// 添加耕织图页面加载时的渐入动画
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        gsap.to(plowContainer, {
          opacity: 1,
          duration: 0.4,
          ease: 'power2.Out',
        });
        // 动画触发后取消观察
        observer.unobserve(plowContainer);
      }
    });
  },
  {
    threshold: 0.1, // 当元素10%进入视口时触发
  }
);

// 开始观察元素
observer.observe(plowContainer);

